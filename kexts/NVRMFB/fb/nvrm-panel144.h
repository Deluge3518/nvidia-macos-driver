static inline bool panel144Matches(const unsigned char *p, unsigned n)
{
    if (!p || n != sizeof kPanel144OriginalEdid) return false;
    for (unsigned i = 0; i < sizeof kPanel144OriginalEdid; ++i)
        if (p[i] != kPanel144OriginalEdid[i]) return false;
    return true;
}
static inline bool panel144RateAllowed(unsigned long long clock, unsigned long long ht, unsigned long long vt)
{
    // Limit both before multiplication; no wrapped malformed timing can pass.
    if (!clock || clock > 0xffffffffULL || !ht || !vt || ht > 65535 || vt > 65535) return false;
    // 0.01 Hz tolerance accommodates the driver's 10 kHz pixel-clock quantization.
    return clock * 1000ULL <= ht * vt * 144010ULL;
}

// Native modes keep upstream behavior; only this downscaled desktop is exposed locally.
static inline bool panel144GeometryAllowed(unsigned w, unsigned h, unsigned rasterW, unsigned rasterH)
{
    return (w == rasterW && h == rasterH) ||
           (w == 3840 && h == 2160 && rasterW == 2560 && rasterH == 1440);
}
